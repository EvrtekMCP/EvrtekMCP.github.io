var SPRITES = {};

function buildSprite(name, rows, ink) {
  var h = rows.length, w = 0, y, x;
  for (y = 0; y < h; y++) w = Math.max(w, rows[y].length);
  var c = document.createElement('canvas');
  c.width = w; c.height = h;
  var g = c.getContext('2d');
  for (y = 0; y < h; y++) {
    for (x = 0; x < rows[y].length; x++) {
      var ch = rows[y][x];
      if (ch === '.' || ch === ' ') continue;
      var key = ink[ch];
      if (!key) continue;
      g.fillStyle = PAL[key];
      g.fillRect(x, y, 1, 1);
    }
  }
  SPRITES[name] = c;
  return c;
}

